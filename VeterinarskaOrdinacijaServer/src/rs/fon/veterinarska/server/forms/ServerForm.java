    private void mbiStartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mbiStartActionPerformed
        if (serverThread != null && serverThread.isAlive()) {
            return;
        }

        try {
            serverThread = new StartServer(SERVER_PORT);
            serverThread.start();
            updateServerStatus(true);
        } catch (IOException ex) {
            serverThread = null;
            updateServerStatus(false);
            System.out.println("Server nije pokrenut: " + ex.getMessage());
            JOptionPane.showMessageDialog(this,
                    "Server ne moze da se pokrene na portu " + SERVER_PORT
                    + ". Proverite da li je port vec zauzet.\n" + ex.getMessage(),
                    "Greska pri pokretanju", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_mbiStartActionPerformed

    private void mbiStopActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mbiStopActionPerformed
        if (serverThread == null || !serverThread.isAlive()) {
            updateServerStatus(false);
            return;
        }

        lblStatusValue.setText("Stopping...");
        panelStatusIcon.setBackground(Color.ORANGE);
        mbiStart.setEnabled(false);
        mbiStop.setEnabled(false);
        mbiConfigure.setEnabled(false);
        serverThread.stopServer();
        // Timer ce prikazati Stopped tek kada se serverska nit zavrsi.
    }//GEN-LAST:event_mbiStopActionPerformed

    private void mbiConfigureActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mbiConfigureActionPerformed
        if (configurationForm == null || !configurationForm.isDisplayable()) {
            configurationForm = new DBConfiguarationForm();
            // Zatvaranje konfiguracije ne sme da ugasi celu aplikaciju.
            configurationForm.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
            configurationForm.setLocationRelativeTo(this);
        }
        configurationForm.setVisible(true);
        configurationForm.toFront();
    }//GEN-LAST:event_mbiConfigureActionPerformed

